import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const contractRepoPath = process.env.CONTRACT_REPO_PATH || 'E:/Roadmap Receipts_V2.3';

console.log('======================================================');
console.log('SYNC EVIDENCE: Copy Evidence to src/data/');
console.log(`Contract repository path: ${contractRepoPath}`);
console.log('======================================================');

let commitSha = '634a6b148326da078ff072a01bef88543a205161';
try {
  commitSha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: contractRepoPath }).toString().trim();
} catch (e) {}

const evidenceSourceDir = path.join(contractRepoPath, 'docs/evidence');
const targetDataDir = path.join(rootDir, 'src/data');

if (!fs.existsSync(targetDataDir)) {
  fs.mkdirSync(targetDataDir, { recursive: true });
}

const filesToSync = [
  { src: 'robustness_results.json', dest: 'robustness_results.json' },
  { src: 'production_sample.json', dest: 'production_sample.json' },
  { src: 'harness_parity.json', dest: 'harness_parity.json' },
  { src: 'onchain_receipts.json', dest: 'lifecycle_receipts.json' },
  { src: 'onchain_readbacks.json', dest: 'lifecycle_readbacks.json' },
  { src: 'reclaim_receipts.json', dest: 'reclaim_receipts.json' },
  { src: 'reclaim_snapshots.json', dest: 'reclaim_snapshots.json' },
  { src: 'error_cases_v2_runs.json', dest: 'error_cases_v2_runs.json' },
  { src: 'finalization/2026-10-31T15-08-45Z.json', dest: 'finalization_summary.json' },
];

for (const f of filesToSync) {
  const srcP = path.join(evidenceSourceDir, f.src);
  const destP = path.join(targetDataDir, f.dest);
  if (!fs.existsSync(srcP)) {
    console.error(`Error: Evidence file missing: ${srcP}`);
    process.exit(1);
  }
  const raw = JSON.parse(fs.readFileSync(srcP, 'utf8'));
  const wrapped = {
    _meta: {
      sourcePath: `docs/evidence/${f.src}`,
      sourceCommit: commitSha,
      sourceRepo: 'hypercybers99/roadmap-receipts-genlayer',
      syncedAt: new Date().toISOString(),
    },
    data: raw,
  };
  fs.writeFileSync(destP, JSON.stringify(wrapped, null, 2), 'utf8');
  console.log(`✓ Synced ${f.src} -> src/data/${f.dest}`);
}

// Also copy raw EXPECTED_VS_ACTUAL.md and LIMITATIONS.md for markdown reference
const expectedVsActualSrc = path.join(contractRepoPath, 'docs/EXPECTED_VS_ACTUAL.md');
if (fs.existsSync(expectedVsActualSrc)) {
  const content = fs.readFileSync(expectedVsActualSrc, 'utf8');
  fs.writeFileSync(path.join(targetDataDir, 'expected_vs_actual.md'), content, 'utf8');
  console.log(`✓ Synced EXPECTED_VS_ACTUAL.md -> src/data/expected_vs_actual.md`);
}

// Generate summary helper TypeScript file for typed UI access
const summaryTs = `// AUTO-GENERATED by scripts/sync_evidence.mjs
// Source commit: ${commitSha}

import robustnessJson from './robustness_results.json';
import prodSampleJson from './production_sample.json';
import harnessParityJson from './harness_parity.json';
import lifecycleReceiptsJson from './lifecycle_receipts.json';
import lifecycleReadbacksJson from './lifecycle_readbacks.json';
import reclaimReceiptsJson from './reclaim_receipts.json';
import reclaimSnapshotsJson from './reclaim_snapshots.json';
import errorCasesJson from './error_cases_v2_runs.json';
import finalizationJson from './finalization_summary.json';

export const EVIDENCE_SOURCE_META = {
  commit: '${commitSha}',
  repo: 'hypercybers99/roadmap-receipts-genlayer',
  tag: 'rr-v1',
};

export const ROBUSTNESS_DATA = robustnessJson.data;
export const PRODUCTION_SAMPLE_DATA = prodSampleJson.data;
export const HARNESS_PARITY_DATA = harnessParityJson.data;
export const LIFECYCLE_RECEIPTS = lifecycleReceiptsJson.data;
export const LIFECYCLE_READBACKS = lifecycleReadbacksJson.data;
export const RECLAIM_RECEIPTS = reclaimReceiptsJson.data;
export const RECLAIM_SNAPSHOTS = reclaimSnapshotsJson.data;
export const ERROR_CASES_DATA = errorCasesJson.data;
export const FINALIZATION_DATA = finalizationJson.data;
`;

fs.writeFileSync(path.join(targetDataDir, 'evidenceSummary.ts'), summaryTs, 'utf8');
console.log(`✓ Generated src/data/evidenceSummary.ts`);
